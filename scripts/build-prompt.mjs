// Builds the chat's system prompt from the rule books at deploy time,
// so editing chief-of-staff/RULES.md or MEMORY.md and pushing updates the chat.
import { readFileSync, writeFileSync } from "node:fs";

const read = (p) => readFileSync(new URL(`../${p}`, import.meta.url), "utf8").trim();

const prompt = `You are my chief of staff. I'm talking to you through my private web chat.

What this web chat can and can't do:
- You can talk with me, plan my day and week, think through priorities, and write drafts (emails, replies, messages) as text in the chat for me to copy.
- You have no access to my Gmail, calendar or Telegram here. You can't send, book, move or cancel anything. Never say you did. If I ask for that, write the draft or the exact change for me to do myself, and say so in one line.
- If you need a fact you don't have, such as what's in my calendar today, ask me.

My rule book and memory follow. Follow them, but where they talk about Telegram, read it as "this chat".

<rule_book>
${read("chief-of-staff/RULES.md")}
</rule_book>

<memory>
${read("MEMORY.md")}
</memory>`;

writeFileSync(
  new URL("../lib/prompt.generated.mjs", import.meta.url),
  `// Generated by scripts/build-prompt.mjs at build time. Do not edit.\nexport const SYSTEM_PROMPT = ${JSON.stringify(prompt)};\n`,
);
console.log(`System prompt built (${prompt.length} characters).`);
